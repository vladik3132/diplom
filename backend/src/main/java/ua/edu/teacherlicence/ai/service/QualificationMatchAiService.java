    /**
     * Спільна реалізація AI-перевірки практичного досвіду (за кафедрою / дисципліною / ОПП).
     * Один system prompt, різні user prompts і cache keys.
     */
    private boolean doPracticalExperienceCheck(
            String position, String organization, String specialtyName,
            String targetCachePrefix,    // "dept:N" / "disc:N" / "prog:N"
            String targetUserContext,    // user-prompt блок з target details
            String logTargetTag           // напр. "discipline='X'"
    ) {
        String safePos = blankOr(position);
        String safeOrg = blankOr(organization);
        String safeSpec = blankOr(specialtyName);
        if ("(відсутні дані)".equals(safePos) && "(відсутні дані)".equals(safeOrg)) return false;

        // v4 — few-shot examples + temperature=0 + org прибрано з ключа
        // (різні редакції назви тієї самої установи мають давати однаковий результат).
        String cacheKey = "pp20:v4:" + targetCachePrefix + "|"
                + safePos.toLowerCase() + "|"
                + safeSpec.toLowerCase();
        Boolean cached = practicalExperienceCache.get(cacheKey);
        if (cached != null) return cached;

        try {
            String userPrompt = """
                    === ВИКЛАДАЧ ===
                    Посада: %s
                    Організація: %s
                    Спеціальність (за договором / трудовою): %s

                    %s
                    """.formatted(safePos, safeOrg, safeSpec, targetUserContext);

            // temperature=0.0 — для повторюваних, стабільних відповідей.
            // Без цього AI давав різні відповіді на ідентичні посади (тільки організація
            // відрізнялась версією назви ВНЗ).
            OpenAiChatOptions deterministic = OpenAiChatOptions.builder()
                    .temperature(0.0)
                    .build();
            ChatClient chatClient = chatClientBuilder.build();
            String response = chatClient.prompt()
                    .options(deterministic)
                    .system(PRACTICAL_EXPERIENCE_SYSTEM_PROMPT)
                    .user(userPrompt)
                    .call()
                    .content();

            boolean matches = parsePracticalExperienceResponse(response);
            practicalExperienceCache.put(cacheKey, matches);
            log.info("AI pp.20 match: {} pos='{}' @ '{}' → {}",
                    logTargetTag, safePos, safeOrg, matches);
            return matches;
        } catch (Exception e) {
            log.warn("AI pp.20 match error for {} pos='{}': {}", logTargetTag, safePos, e.getMessage());
            return false;
        }
    }

    private boolean parsePracticalExperienceResponse(String response) {
        try {
            String json = extractJson(response);
            JsonNode node = objectMapper.readTree(json);
            return node.has("matches") && node.get("matches").asBoolean(false);
        } catch (Exception e) {
            log.warn("Failed to parse pp.20 AI response: {}", response);
            return false;
        }
    }

    public void clearCache() {
        cache.clear();
        practicalExperienceCache.clear();
    }

    public void clearCacheForTeacher(Long teacherId) {
        cache.keySet().removeIf(k -> k.startsWith(teacherId + ":"));
    }

    public void clearCacheForDiscipline(Long disciplineId) {
        cache.keySet().removeIf(k -> k.contains(":D:" + disciplineId));
    }

    public void clearCacheForProgram(Long programId) {
        cache.keySet().removeIf(k -> k.contains(":P:" + programId));
    }
