    private MatchResult parseResponse(String response, boolean hasUnivSpec, boolean hasDegree) {
        try {
            String json = extractJson(response);
            JsonNode node = objectMapper.readTree(json);
            boolean diplomaMatches = node.has("diplomaMatches") && node.get("diplomaMatches").asBoolean(false);
            boolean degreeMatches = node.has("degreeMatches") && node.get("degreeMatches").asBoolean(false);
            return new MatchResult(diplomaMatches && hasUnivSpec, degreeMatches && hasDegree);
        } catch (Exception e) {
            log.warn("Failed to parse AI qualification match response: {}", response);
            return new MatchResult(hasUnivSpec, hasDegree);
        }
    }

    private String extractJson(String text) {
        Pattern pattern = Pattern.compile("\\{[^}]+}");
        Matcher matcher = pattern.matcher(text);
        if (matcher.find()) {
            return matcher.group();
        }
        return text.trim();
    }

