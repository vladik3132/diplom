package ua.edu.teacherlicence.ppdata.model;

/**
 * Роль в атестації наукових кадрів (пп.7).
 *
 * <p>Перші три ролі — РАЗОВІ (одна участь у конкретному захисті);
 * для виконання пп.7 потрібно ≥3 таких в сумі.
 * {@link #COUNCIL_MEMBER} — ТРИВАЮЧА (членство у постійній спецраді);
 * 1 факту достатньо для виконання пп.7.
 */
public enum AttestationRole {
    /** Офіційний опонент дисертації — разова участь. */
    OPPONENT,
    /** Рецензент дисертації — разова участь. */
    REVIEWER,
    /** Голова разової спеціалізованої вченої ради — разова участь. */
    CHAIR,
    /** Член постійної спеціалізованої вченої ради — триваюча роль (період). */
    COUNCIL_MEMBER
}
