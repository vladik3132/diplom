package ua.edu.teacherlicence.ppdata.model;

/**
 * Тип діяльності за пп.14 — різні форми роботи зі здобувачами освіти.
 *
 * Відповідно до Ліцензійних умов, пп.14 охоплює:
 * - Олімпіади/конкурси (міжнародні, всеукраїнські, галузеві)
 * - Наукові гуртки / наукові товариства
 * - Спортивні змагання (тренер збірної)
 * - Мистецькі конкурси
 * - Конкурси наукових робіт, МАН
 * - Інші форми наукової/творчої роботи зі студентами
 */
public enum Pp14ActivityType {

    /** Олімпіада з навчальної дисципліни */
    OLYMPIAD,

    /** Конкурс наукових робіт (вкл. МАН) */
    SCIENTIFIC_COMPETITION,

    /** Конкурс (хакатон, технічний, творчий конкурс тощо) */
    COMPETITION,

    /** Постійно діючий науковий гурток */
    SCIENTIFIC_GROUP,

    /** Спортивні змагання / тренерство збірної */
    SPORTS,

    /** Мистецький конкурс / творчі виступи */
    ARTS,

    /** Інше (не потрапляє в жодну категорію) */
    OTHER
}
